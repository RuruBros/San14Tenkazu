"""Generate version-bound managed/native facts. Uses only authored files, never a game process."""
import argparse
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent
MANIFEST = HERE / 'current.json'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def load(path=MANIFEST, source=SOURCE):
    raw = path.read_bytes()
    profile = json.loads(raw)
    if profile['schemaVersion'] != 1 or not re.fullmatch(r'[a-z0-9-]+', profile['id']):
        raise ValueError('Unsupported profile schema/identity')
    if not re.fullmatch(r'[0-9A-F]{64}', profile['exeSha256']):
        raise ValueError('Invalid executable hash')
    for key in ('layoutId', 'nativeContractId', 'processName'):
        if not re.fullmatch(r'[A-Za-z0-9_-]+', profile[key]):
            raise ValueError('Invalid profile identity: ' + key)
    for group, facts in profile['groups'].items():
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', group):
            raise ValueError('Invalid fact group')
        for name, fact in facts.items():
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', name):
                raise ValueError('Invalid fact name')
            limit = {'int': 0x7fffffff, 'uint': 0xffffffff, 'ulong': 0xffffffffffffffff}.get(fact['type'])
            if limit is None or type(fact['value']) is not int or not 0 <= fact['value'] <= limit:
                raise ValueError('Invalid fact type/range: ' + name)
    names = set()
    for resource in profile['resources']:
        path = (source / resource['path']).resolve()
        if not path.is_relative_to(source.resolve()) or resource['name'] in names:
            raise ValueError('Invalid/duplicate resource')
        names.add(resource['name'])
        if sha(path.read_bytes()) != resource['sha256']:
            raise ValueError('Profile resource differs: ' + resource['name'])
    all_arrays = {}
    for name, declaration in profile['abi'].items():
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', name) or not re.fullmatch(r'(void|uint8_t|int)\(__fastcall\*\)\((void\*|uint32_t|int)(,(void\*|uint32_t|int))*\)', declaration):
            raise ValueError('Invalid Native ABI declaration')
    for spec in profile['signatures'].values():
        for array in spec['arrays']:
            data = bytes.fromhex(array['bytes'])
            if not data or sha(data) != array['sha256'] or array['name'] in all_arrays:
                raise ValueError('Invalid/duplicate native signature')
            all_arrays[array['name']] = data
    bindings = {'Season': ['DrawCode', 'LandCode', 'MeshCode', 'ExpectedPrepareCode', 'IndexedCode', 'BatchCode'],
                'Environment': ['AppUpdateCode', 'MoveSpeedCode', 'AddMoraleCode']}
    rvas = {'Season': ['DrawRva', 'LandRva', 'MeshRva', 'PrepareRva', 'IndexedRva', 'BatchRva'],
            'Environment': ['UpdateRva', 'MoveSpeedRva', 'AddMoraleRva']}
    for kind, arrays in bindings.items():
        guards = profile['guards'][kind]
        if len(guards) != len(arrays):
            raise ValueError('Native guard count differs')
        for guard, array, rva in zip(guards, arrays, rvas[kind]):
            data = all_arrays[array]
            if guard != dict(rva=profile['groups']['Engine'][rva]['value'], size=len(data), sha256=sha(data)):
                raise ValueError('Managed/native guard differs: ' + array)
    return profile, sha(raw)


def outputs(profile, digest):
    lines = ['// Generated by source/BuildProfiles/generate.py. Do not edit.',
             'namespace San14Tenkazu;', '', 'internal static class GameBuildFacts', '{']
    for key, value in [('Id', profile['id']), ('Sha256', digest), ('ExeSha256', profile['exeSha256']),
                       ('ProcessName', profile['processName']), ('LayoutId', profile['layoutId']),
                       ('NativeContractId', profile['nativeContractId'])]:
        lines.append(f'    internal const string {key} = "{value}";')
    native = ['// Generated by source/BuildProfiles/generate.py. Do not edit.', '#pragma once', '#include <cstdint>',
              f'#define SAN14_BUILD_PROFILE_IDENTITY "{profile["id"]}:{digest}:{profile["nativeContractId"]}"',
              'namespace gamebuild {']
    for group, facts in profile['groups'].items():
        lines += [f'    internal static class {group}', '    {']
        native += [f'namespace {group} {{']
        for name, fact in facts.items():
            typ, value = fact['type'], fact['value']
            suffix = {'int': '', 'uint': 'U', 'ulong': 'UL'}[typ]
            lines.append(f'        internal const {typ} {name} = 0x{value:X}{suffix};')
            ctyp, suffix = {'int': ('int32_t', ''), 'uint': ('uint32_t', 'U'), 'ulong': ('uint64_t', 'ULL')}[typ]
            native.append(f'inline constexpr {ctyp} {name}=0x{value:x}{suffix};')
        lines.append('    }')
        native.append('}')
    lines += ['    internal static class NativeAbi', '    {']
    native += ['namespace Abi {']
    for name, declaration in profile['abi'].items():
        lines.append(f'        internal const string {name} = "{declaration}";')
        native.append(f'using {name}={declaration};')
    lines.append('    }')
    native.append('}')
    for kind, guards in profile['guards'].items():
        lines += [f'    internal static (ulong Rva, int Size, string Hash)[] {kind}Targets() =>', '    [']
        lines += [f'        (0x{g["rva"]:X}UL, {g["size"]}, "{g["sha256"]}"),' for g in guards]
        lines.append('    ];')
    lines += ['    internal static System.Collections.Generic.IReadOnlyDictionary<string, string> Resources() =>',
              '        new System.Collections.ObjectModel.ReadOnlyDictionary<string, string>(new System.Collections.Generic.Dictionary<string, string>', '        {']
    lines += [f'            ["{r["name"]}"] = "{r["sha256"]}",' for r in profile['resources']]
    lines += ['        });', '}']
    native += ['}', '']
    result = {'Core/BuildProfiles/GameBuildFacts.g.cs': '\n'.join(lines) + '\n'}
    for kind in ('Seasons', 'Environment'):
        result[f'{kind}/Native/GameBuildFacts.g.h'] = '\n'.join(native)
    for path, spec in profile['signatures'].items():
        lines = ['// Generated exact original bytes from BuildProfiles/current.json.', '#pragma once', '#include <cstdint>']
        if spec['namespace']:
            lines.append(f'namespace {spec["namespace"]} {{')
        for array in spec['arrays']:
            lines.append(f'inline constexpr unsigned char {array["name"]}[]={{')
            data = bytes.fromhex(array['bytes'])
            for start in range(0, len(data), 24):
                lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[start:start+24]) + ',')
            lines.append('};')
        if spec['namespace']:
            lines.append('}')
        result[path] = '\n'.join(lines) + '\n'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    profile, digest = load()
    generated = outputs(profile, digest)
    lock = {'schemaVersion': 1, 'profileSha256': digest,
            'files': {p: sha(content.encode()) for p, content in generated.items()}}
    generated['BuildProfiles/generated.lock.json'] = json.dumps(lock, indent=2) + '\n'
    for name, content in generated.items():
        path = SOURCE / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                raise ValueError('Stale generated file: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode())
    print(f'PASS build profile {profile["id"]}: {len(generated)} generated files; no game access')


if __name__ == '__main__':
    main()
